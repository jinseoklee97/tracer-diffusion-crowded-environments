clear all;
close all;
clc;

%% Code for doing multiple particle tracking + NGP/VACF analysis

maxdisp = 10;   % maximum displacement in pixel

nt = 2000;      % number of frames
dt = 0.5;       % frame interval [s]

pxsz = 0.293;   % pixel size [um/pixel]
% pxsz = 0.1465;
% pxsz = 1;

filename = '0.72';

filestemShort = strcat(filename, '.tif');
exportstem    = filename;
exportLoc     = 'Results/';

if ~exist(exportLoc, 'dir')
    mkdir(exportLoc);
end

FR = 1/dt;

tStart = tic;

[lub, MSDMic, stdDevMic, tauS, ...
 alpha2_r, alpha2_x, alpha2_y, tauStats, ...
 tauVACF, VACF, VACF_norm, VACF_count] = ...
    MPT_perform(filestemShort, FR, pxsz, nt, exportstem, exportLoc, maxdisp);

runtime = toc(tStart);

fprintf('Total runtime = %.3f seconds\n', runtime);

%% Save original outputs
save(fullfile(exportLoc, [filename '_MSD.mat']),   'MSDMic');
save(fullfile(exportLoc, [filename '_stDev.mat']), 'stdDevMic');
save(fullfile(exportLoc, [filename '_tau.mat']),   'tauS');
save(fullfile(exportLoc, [filename '_lub.mat']),   'lub');

%% Save NGP outputs
save(fullfile(exportLoc, [filename '_NGP.mat']), ...
    'tauS', 'alpha2_r', 'alpha2_x', 'alpha2_y', 'tauStats');

T_ngp = table( ...
    tauS(:), ...
    MSDMic(:), ...
    stdDevMic(:), ...
    alpha2_r(:), ...
    alpha2_x(:), ...
    alpha2_y(:), ...
    'VariableNames', { ...
    'tau_s', ...
    'MSD_um2_original_MPT_perform', ...
    'stdDev_um2_original_MPT_perform', ...
    'alpha2_r', ...
    'alpha2_x', ...
    'alpha2_y'});

writetable(T_ngp, fullfile(exportLoc, [filename '_MSD_NGP_noEB_runner.csv']));

%% Save VACF outputs
save(fullfile(exportLoc, [filename '_VACF.mat']), ...
    'tauVACF', 'VACF', 'VACF_norm', 'VACF_count');

T_vacf = table( ...
    tauVACF(:), ...
    VACF(:), ...
    VACF_norm(:), ...
    VACF_count(:), ...
    'VariableNames', { ...
    'tau_s', ...
    'VACF_um2_per_s2', ...
    'VACF_normalized', ...
    'nVelocityPairs'});

writetable(T_vacf, fullfile(exportLoc, [filename '_VACF_runner.csv']));

%% Save one combined result file
save(fullfile(exportLoc, [filename '_MPT_MSD_NGP_VACF_noEB_all.mat']), ...
    'lub', ...
    'MSDMic', ...
    'stdDevMic', ...
    'tauS', ...
    'alpha2_r', ...
    'alpha2_x', ...
    'alpha2_y', ...
    'tauStats', ...
    'tauVACF', ...
    'VACF', ...
    'VACF_norm', ...
    'VACF_count', ...
    'maxdisp', ...
    'nt', ...
    'dt', ...
    'FR', ...
    'pxsz', ...
    'filename', ...
    'runtime');

fprintf('Saved MSD, NGP, and VACF outputs to %s\n', exportLoc);